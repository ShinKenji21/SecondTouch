"""Generate a synthetic football dataset from the SecondTouch simulator.

    python export_dataset.py --matches 20 --seed 1 --out ../data/synthetic

Writes, per run:
  events.jsonl    one event per line, with all 22 player positions after it
  events.csv      the same events, flat (no positions)
  players.csv     one row per player per match with the full stat line
  matches.csv     one row per match: metadata, score, xG, possession
  README.md       field descriptions
Every value is generated; no real match data is involved.
"""
import argparse
import csv
import json
from pathlib import Path

from analytics import MatchStats
from generator import AWAY, FORMATIONS, HOME, SQUADS, MatchSim

EVENT_COLS = ["match_id", "seq", "minute", "clock", "team", "player", "event_type", "outcome", "receiver",
              "opponent", "player_off", "card", "set_piece", "restart", "restart_team", "body_part", "length_m", "start_x", "start_y", "end_x", "end_y", "xg",
              "pass_difficulty", "pressure", "pressure_index", "nearest_defender_m", "sprint_speed_kmh",
              "ball_speed_kmh", "forward_gain_m", "players_bypassed", "possession_change", "right_team",
              "is_impact_moment", "impact_reasons", "score_home", "score_away"]

FIELD_DOC = """# SecondTouch synthetic dataset

Generated by `backend/export_dataset.py`. Every value is simulated.

Coordinates are percentages of a 105 x 68 m pitch, x left to right, y top to bottom.
`right_team` is the team attacking towards x = 100 (teams change ends at half-time).

## events.csv / events.jsonl
| field | meaning |
|---|---|
| match_id, seq | match number in this export, event number within the match |
| minute, clock | match time |
| team, player | acting team and player (for TACKLE: the tackler) |
| event_type | PASS, DRIBBLE, SHOT, TACKLE, SUBSTITUTION, HALF_TIME, FULL_TIME |
| outcome | PASS: COMPLETE/INTERCEPTED/OUT (out of play)/OFFSIDE; DRIBBLE: SUCCESS; TACKLE: WON/FOUL; SHOT: GOAL/SAVED/MISS/BLOCKED |
| receiver, opponent, player_off, card | pass receiver (for OFFSIDE: the player flagged); opposing player involved; player substituted off; YELLOW/RED |
| set_piece | this action restarts play: FREE_KICK, CORNER, THROW_IN, PENALTY or GOAL_KICK (a corner is a PASS, a penalty a SHOT) |
| restart, restart_team | play stopped after this action and restarts with this set piece, taken by this team |
| body_part | shots: FOOT or HEAD (headers mostly come from corners) |
| start_x..end_y | where the action started and ended |
| xg | expected goals of a shot (distance, angle, pressure) |
| pass_difficulty | 5-99 from length, direction, pressure and receiver space |
| pressure, pressure_index, nearest_defender_m | defensive pressure on the player on the ball |
| sprint_speed_kmh | dribbler's speed, or a runner's speed onto a through ball |
| ball_speed_kmh | pass or shot speed |
| forward_gain_m, players_bypassed | pass progression |
| possession_change | true when the other team has the ball after this event |
| is_impact_moment, impact_reasons | the engine's highlight filter |
| score_home, score_away | score after the event |

events.jsonl adds `positions`: {team: {player: [x, y]}} after the event.

## players.csv
One row per player per match: minutes, rating, goals, assists, shots, xG, passes, key passes,
line breaks, dribbles, tackles, interceptions, fouls, fouls won, offsides, cards, saves, touches, sprints,
distance (km), top speed (km/h).

## matches.csv
Metadata (competition, venue, referee, weather, seed) and final score, xG, shots and possession.
"""


def flat(match_id, ev):
    m, loc = ev["metrics"], ev["location"]
    row = {k: ev.get(k) for k in EVENT_COLS if k in ev}
    row.update(match_id=match_id, start_x=loc["start_x"], start_y=loc["start_y"], end_x=loc["end_x"],
               end_y=loc["end_y"], impact_reasons="|".join(ev["impact_reasons"]),
               score_home=ev["score"]["home"], score_away=ev["score"]["away"], **m)
    return {k: row.get(k) for k in EVENT_COLS}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--matches", type=int, default=10)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "data" / "synthetic"))
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    with open(out / "events.jsonl", "w", encoding="utf-8") as fj, \
            open(out / "events.csv", "w", newline="", encoding="utf-8") as fe, \
            open(out / "players.csv", "w", newline="", encoding="utf-8") as fp, \
            open(out / "matches.csv", "w", newline="", encoding="utf-8") as fm:
        ew = csv.DictWriter(fe, fieldnames=EVENT_COLS)
        ew.writeheader()
        pw = mw = None
        total = 0
        for i in range(args.matches):
            match_id = i + 1
            sim = MatchSim(seed=args.seed + i)
            stats = MatchStats(SQUADS, FORMATIONS, HOME, AWAY)
            last = None
            while (ev := sim.next_event()) is not None:
                stats.update(ev, sim.positions, sim.possession)
                fj.write(json.dumps({"match_id": match_id, **ev, "positions": sim.positions}, ensure_ascii=False) + "\n")
                ew.writerow(flat(match_id, ev))
                last, total = ev, total + 1
            for team in (HOME, AWAY):
                for r in stats.player_rows(team):
                    row = {"match_id": match_id, "team": team, **r}
                    if pw is None:
                        pw = csv.DictWriter(fp, fieldnames=list(row))
                        pw.writeheader()
                    pw.writerow(row)
            s = stats.summary()
            meta = {k: v for k, v in sim.metadata.items() if not isinstance(v, (dict, list))}
            row = {"match_id": match_id, **meta, "score_home": last["score"]["home"],
                   "score_away": last["score"]["away"], "xg_home": s["xg"][0], "xg_away": s["xg"][1],
                   "shots_home": s["shots"][0], "shots_away": s["shots"][1],
                   "possession_home": s["possession"][0], "possession_away": s["possession"][1]}
            if mw is None:
                mw = csv.DictWriter(fm, fieldnames=list(row))
                mw.writeheader()
            mw.writerow(row)
    (out / "README.md").write_text(FIELD_DOC, encoding="utf-8")
    print(f"Wrote {args.matches} matches, {total} events to {out}")


if __name__ == "__main__":
    main()
